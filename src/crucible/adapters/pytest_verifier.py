"""Verifier that runs hidden pytest tests in a fresh container.

Trust model:

* ``prepare`` first builds a *verifier base*: the environment image with the workdir
  deleted. It then builds the task's ``tests/Dockerfile`` on top of that base; the
  Dockerfile copies the hidden tests to ``/tests``. The agent's container comes from
  the environment image only, so the tests never exist there.
* ``verify`` starts a new container from the verifier image, checks that the workdir
  is absent or empty, extracts the agent's workspace snapshot into it, and runs pytest.
  The snapshot is therefore the only agent-controlled input: the interpreter, installed
  packages and tests all come from the image.
* pytest is pinned to ``/tests`` as rootdir and confcutdir, so configuration or
  ``conftest.py`` files the agent may have left in the workspace are never loaded, and
  the workspace is deliberately not on ``PYTHONPATH`` (that would import an
  agent-supplied ``sitecustomize``). Tests import the workspace explicitly; see
  ``docs/authoring-a-task.md``.
"""

from __future__ import annotations

import logging
import tempfile
import time
from pathlib import Path
from typing import Protocol

from crucible.domain.schema import Task, Verdict
from crucible.errors import SandboxTimeoutError, VerifierError
from crucible.images import content_digest, digest_of, image_tag
from crucible.ports.sandbox import ExecResult, ImageRef, SandboxBackend, WorkspaceSnapshot

log = logging.getLogger(__name__)


class SandboxExec(Protocol):
    def __call__(self, command: str, *, timeout: float) -> ExecResult: ...


TESTS_DIR = "/tests"
BASE_IMAGE_ARG = "BASE_IMAGE"

VERIFIER_BASE_DOCKERFILE = """\
# Generated by crucible. The verifier base is the environment image minus the workdir,
# so the only workdir content a verifier container can ever see is the agent's snapshot.
ARG BASE_IMAGE
FROM ${BASE_IMAGE}
ARG BASE_USER
ARG WORKDIR
USER root
RUN rm -rf -- "${WORKDIR}"
USER ${BASE_USER}
"""

# pytest exit codes (see pytest.ExitCode).
_EXIT_OK = 0
_EXIT_TESTS_FAILED = 1
_EXIT_INTERRUPTED = 2
_EXIT_NO_TESTS_COLLECTED = 5

_HOUSEKEEPING_TIMEOUT = 30.0


class PytestVerifier:
    def __init__(self, backend: SandboxBackend, *, output_limit: int = 20_000) -> None:
        self._backend = backend
        self._output_limit = output_limit
        self._image: ImageRef | None = None

    def prepare(self, task: Task, environment: ImageRef) -> tuple[ImageRef, ...]:
        build_timeout = task.config.environment.build_timeout_seconds
        with tempfile.TemporaryDirectory(prefix="crucible-verifier-base-") as tmp:
            context = Path(tmp)
            (context / "Dockerfile").write_text(VERIFIER_BASE_DOCKERFILE, encoding="utf-8")
            base = self._backend.build_image(
                context,
                tag=image_tag(
                    task.name,
                    "verifier-base",
                    digest_of(VERIFIER_BASE_DOCKERFILE, environment.id, task.workdir),
                ),
                build_args={
                    BASE_IMAGE_ARG: environment.tag,
                    "BASE_USER": environment.user,
                    "WORKDIR": task.workdir,
                },
                timeout=build_timeout,
            )
        self._image = self._backend.build_image(
            task.tests_dir,
            tag=image_tag(task.name, "verifier", content_digest(task.tests_dir, extra=base.id)),
            build_args={BASE_IMAGE_ARG: base.tag},
            timeout=build_timeout,
        )
        return (base, self._image)

    def verify(self, task: Task, snapshot: WorkspaceSnapshot) -> Verdict:
        if self._image is None:
            msg = "verify() called before prepare()"
            raise VerifierError(msg)
        if snapshot.root != task.workdir:
            msg = f"snapshot was taken from {snapshot.root}, expected {task.workdir}"
            raise VerifierError(msg)
        timeout = task.config.verifier.timeout_seconds
        started = time.monotonic()
        command = (
            "python -m pytest -q -rA -p no:cacheprovider "
            f"--rootdir={TESTS_DIR} --confcutdir={TESTS_DIR} {TESTS_DIR}"
        )
        with self._backend.start(self._image, workdir=TESTS_DIR, limits=task.limits) as sandbox:
            self._assert_workdir_clean(sandbox_exec=sandbox.exec, workdir=task.workdir)
            sandbox.restore(snapshot)
            try:
                result = sandbox.exec(command, timeout=timeout)
            except SandboxTimeoutError:
                log.info("verifier timed out after %.0fs", timeout)
                return Verdict(
                    passed=False,
                    exit_code=None,
                    output=f"verifier timed out after {timeout:.0f}s",
                    duration_seconds=time.monotonic() - started,
                )

        output = self._tail(result.stdout + result.stderr)
        duration = time.monotonic() - started
        if result.exit_code in (_EXIT_OK, _EXIT_TESTS_FAILED, _EXIT_INTERRUPTED):
            passed = result.exit_code == _EXIT_OK
            log.info(
                "verifier: %s (exit %d, %.1fs)",
                "pass" if passed else "fail",
                result.exit_code,
                duration,
            )
            return Verdict(
                passed=passed, exit_code=result.exit_code, output=output, duration_seconds=duration
            )
        if result.exit_code == _EXIT_NO_TESTS_COLLECTED:
            msg = f"no tests collected under {TESTS_DIR}; is the verifier Dockerfile copying them?"
            raise VerifierError(msg)
        msg = f"pytest exited with unexpected code {result.exit_code}:\n{output}"
        raise VerifierError(msg)

    @staticmethod
    def _assert_workdir_clean(*, sandbox_exec: SandboxExec, workdir: str) -> None:
        quoted = "'" + workdir.replace("'", "'\\''") + "'"
        probe = sandbox_exec(
            f'[ ! -e {quoted} ] || [ -z "$(ls -A {quoted})" ]',
            timeout=_HOUSEKEEPING_TIMEOUT,
        )
        if not probe.ok:
            msg = (
                f"verifier image contains files under {workdir}; tests/Dockerfile must not "
                "write into the workdir"
            )
            raise VerifierError(msg)

    def _tail(self, text: str) -> str:
        if len(text) <= self._output_limit:
            return text
        return "[... truncated ...]\n" + text[-self._output_limit :]
